export type IconName = keyof typeof PATHS;

export interface IconProps {
  name: IconName;
  size?: number;
  className?: string;
  /** Extra stroke width override (defaults vary subtly by icon family). */
  strokeWidth?: number;
}

export function Icon({ name, size = 18, className = "", strokeWidth = 2 }: IconProps): JSX.Element {
  const inner: ReactNode = PATHS[name];
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      aria-hidden="true"
    >
      {inner}
    </svg>
  );
}

/** Runtime check — useful for tests + dynamic icon names. */
export function isIconName(value: unknown): value is IconName {
  return typeof value === "string" && Object.prototype.hasOwnProperty.call(PATHS, value);
}

