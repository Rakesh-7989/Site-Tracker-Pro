#!/usr/bin/env node
// SiteTrack Pro — generate the committed public Supabase config from .env.local.
//
// The Supabase project URL + ANON key are PUBLIC (the anon key is RLS-protected
// and is downloaded by every browser anyway). Baking them into a committed
// module means the production build connects to Supabase even when the Vercel
// build-time VITE_* env vars are absent (which is what caused "backend-disabled").
//
// Re-run this if the project URL / anon key ever changes.
// Usage:  node scripts/gen-public-config.mjs

import { readFileSync, existsSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const envPath = join(root, ".env.local");
if (!existsSync(envPath)) { console.error("❌ .env.local missing"); process.exit(1); }
const env = Object.fromEntries(
  readFileSync(envPath, "utf8").split(/\r?\n/)
    .map(l => l.match(/^([A-Z_][A-Z0-9_]*)=(.*)$/)).filter(Boolean)
    .map(m => [m[1], m[2].replace(/^"|"$/g, "").trim()])
);

const url = env.VITE_SUPABASE_URL;
const anon = env.VITE_SUPABASE_ANON_KEY;
if (!url || !anon) { console.error("❌ VITE_SUPABASE_URL / VITE_SUPABASE_ANON_KEY missing in .env.local"); process.exit(1); }
if (!/^https:\/\/[a-z0-9]+\.supabase\.co$/.test(url)) { console.error(`❌ URL looks wrong: ${url}`); process.exit(1); }
// Sanity: anon JWT should decode to role "anon" (never ship service_role).
try {
  const payload = JSON.parse(Buffer.from(anon.split(".")[1], "base64url").toString("utf8"));
  if (payload.role !== "anon") { console.error(`❌ key role is "${payload.role}", expected "anon" — refusing to commit`); process.exit(1); }
} catch { console.error("❌ could not decode anon key as a JWT"); process.exit(1); }

const out = `// AUTO-GENERATED by scripts/gen-public-config.mjs -- do not edit by hand.
//
// Public Supabase config for the production build. The anon key is RLS-protected
// and is downloaded by every browser regardless, so committing it is safe (it is
// NOT the service_role key). This is a FALLBACK: import.meta.env.VITE_* always
// wins when present (local dev + any properly-configured deployment).
export const PUBLIC_SUPABASE_URL: string = ${JSON.stringify(url)};
export const PUBLIC_SUPABASE_ANON_KEY: string = ${JSON.stringify(anon)};
`;
const dest = join(root, "src", "lib", "supabase", "supabasePublicConfig.ts");
writeFileSync(dest, out, "utf8");
console.log(`✅ wrote src/lib/supabase/supabasePublicConfig.ts  (url ${url}, anon role=anon, len ${anon.length})`);
