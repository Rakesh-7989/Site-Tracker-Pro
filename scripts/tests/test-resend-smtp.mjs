#!/usr/bin/env node
// SiteTrack Pro — Sprint 1 hotfix (Session 30.7): Resend SMTP precheck.
//
// Verifies your Resend API key + sender are wired correctly BEFORE you
// drop them into Supabase Auth's SMTP settings. Sends one test email and
// reports the Resend message_id or the exact failure reason.
//
// Usage:
//   RESEND_API_KEY=re_xxx \
//   RESEND_FROM=hello@sitetrackpro.in \
//     node scripts/test-resend-smtp.mjs you@example.com
//
//   # Or pass everything as CLI args:
//   node scripts/test-resend-smtp.mjs --key re_xxx --from hello@sitetrackpro.in --to you@example.com
//
// Exit codes:
//   0 = success (you'll see message_id; check the recipient inbox)
//   1 = misconfiguration or Resend API rejected the request
//
// Why this script exists: in docs/setup/RESEND_SMTP_SETUP.md the founder pastes
// the same API key into Supabase Auth. Verifying it works here first
// avoids the 30-minute "I configured everything but emails still don't
// send" rabbit hole.

const args = process.argv.slice(2);
function arg(name) {
  const idx = args.indexOf(`--${name}`);
  return idx !== -1 && args[idx + 1] ? args[idx + 1] : null;
}

const apiKey = arg("key") || process.env.RESEND_API_KEY;
const from   = arg("from") || process.env.RESEND_FROM;
const to     = arg("to") || args.find(a => a.includes("@") && !a.startsWith("--"));

if (!apiKey || !from || !to) {
  console.error("Usage:");
  console.error("  RESEND_API_KEY=re_xxx RESEND_FROM=sender@domain node scripts/test-resend-smtp.mjs recipient@domain");
  console.error("  -OR-");
  console.error("  node scripts/test-resend-smtp.mjs --key re_xxx --from sender@domain --to recipient@domain");
  console.error("");
  console.error(`Got: key=${apiKey ? "set" : "MISSING"}, from=${from || "MISSING"}, to=${to || "MISSING"}`);
  process.exit(1);
}

if (!apiKey.startsWith("re_")) {
  console.error(`⚠️  API key doesn't start with 're_' — are you sure this is a Resend API key (not the key name)?`);
}

console.log(`Sending test email …`);
console.log(`  From:    ${from}`);
console.log(`  To:      ${to}`);
console.log(`  API key: ${apiKey.slice(0, 6)}…${apiKey.slice(-4)}`);

const body = {
  from,
  to: [to],
  subject: "SiteTrack Pro · Resend SMTP test",
  html: `
    <div style="font-family:Inter,Arial,sans-serif;max-width:480px;margin:32px auto;padding:24px;border:1px solid #e5e1d8;border-radius:12px;background:#fffaf0">
      <div style="font-size:11px;font-weight:700;letter-spacing:0.18em;text-transform:uppercase;color:#d97706;margin-bottom:12px">SiteTrack Pro · SMTP precheck</div>
      <div style="font-size:18px;font-weight:600;color:#1c1917;margin-bottom:8px">Your Resend SMTP setup is working.</div>
      <p style="font-size:14px;color:#44403c;line-height:1.5;margin:0 0 16px 0">
        If you're reading this, the Resend API key + sender combination is good. Paste them into Supabase Auth SMTP Settings and the next signup will receive its verification email via this path.
      </p>
      <p style="font-size:12px;color:#78716c;line-height:1.5;margin:0">
        Generated by <code>scripts/test-resend-smtp.mjs</code> · ${new Date().toISOString()}
      </p>
    </div>
  `.trim(),
  text: `SiteTrack Pro Resend precheck. If you got this, the API key + sender combination is correct. Sent ${new Date().toISOString()}.`,
};

try {
  const res = await fetch("https://api.resend.com/emails", {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      Authorization: `Bearer ${apiKey}`,
    },
    body: JSON.stringify(body),
  });
  const text = await res.text();
  let parsed;
  try { parsed = JSON.parse(text); } catch { parsed = null; }

  if (res.ok && parsed?.id) {
    console.log(`\n✅ SENT — message_id=${parsed.id}`);
    console.log(`   Check the ${to} inbox (also check spam).`);
    console.log(`\nNext step → paste your API key into Supabase Auth:`);
    console.log(`   https://supabase.com/dashboard/project/nntkxojdeyziemdhyjvg/auth/templates`);
    console.log(`   See docs/setup/RESEND_SMTP_SETUP.md Step 4 for the exact fields.`);
    process.exit(0);
  }

  console.error(`\n❌ FAILED — HTTP ${res.status}`);
  if (parsed?.message) console.error(`   message: ${parsed.message}`);
  if (parsed?.name)    console.error(`   name:    ${parsed.name}`);

  console.error(`\n📖 Common fixes:`);
  if (res.status === 401 || /invalid|unauthorized/i.test(parsed?.message || "")) {
    console.error(`  • API key invalid → regenerate at resend.com → API Keys → New`);
  }
  if (res.status === 403 || /domain|sender|verify/i.test(parsed?.message || "")) {
    console.error(`  • Sender not verified → resend.com → Domains → Verify`);
    console.error(`    (or use the verified Single Sender path in docs/setup/RESEND_SMTP_SETUP.md Step 2a)`);
  }
  if (res.status === 422) {
    console.error(`  • Recipient invalid → make sure ${to} is a real address`);
  }
  if (res.status === 429) {
    console.error(`  • Resend rate limit hit (rare on free tier) → wait 60s + retry`);
  }
  console.error(`\nFull response body:\n${text.slice(0, 800)}`);
  process.exit(1);
} catch (e) {
  console.error(`\n❌ Network error: ${e.message}`);
  process.exit(1);
}
